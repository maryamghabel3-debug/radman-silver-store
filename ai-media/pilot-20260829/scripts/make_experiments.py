# ---------- product extraction ----------

def product_cutout(fn):
    """Return RGBA cutout of the ring + its bbox from the cleaned master."""
    img = cv2.imread(os.path.join(CLEAN, fn))
    H, W = img.shape[:2]
    small = cv2.resize(img, (400, 400), interpolation=cv2.INTER_AREA)
    mask = np.zeros(small.shape[:2], np.uint8)
    rect = (int(400*0.14), int(400*0.02), int(400*0.72), int(400*0.92))
    bgd, fgd = np.zeros((1, 65), np.float64), np.zeros((1, 65), np.float64)
    cv2.grabCut(small, mask, rect, bgd, fgd, 6, cv2.GC_INIT_WITH_RECT)
    m2 = np.where((mask == cv2.GC_FGD) | (mask == cv2.GC_PR_FGD), 255, 0).astype(np.uint8)
    m2 = cv2.morphologyEx(m2, cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
    m2 = cv2.morphologyEx(m2, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
    n, lab, stats, _ = cv2.connectedComponentsWithStats(m2, 8)
    if n > 1:
        big = 1 + np.argmax(stats[1:, cv2.CC_STAT_AREA])
        m2 = np.where(lab == big, 255, 0).astype(np.uint8)
    # largest-contour fill to solidify
    cnts, _ = cv2.findContours(m2, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if cnts:
        c = max(cnts, key=cv2.contourArea)
        fill = np.zeros_like(m2)
        cv2.drawContours(fill, [c], -1, 255, -1)
        m2 = cv2.bitwise_and(fill, cv2.dilate(m2, np.ones((5, 5), np.uint8)))
    mask_full = cv2.resize(m2, (W, H), interpolation=cv2.INTER_LINEAR)
    mask_full = cv2.GaussianBlur(mask_full, (0, 0), 1.2)
    rgba = cv2.cvtColor(img, cv2.COLOR_BGR2BGRA)
    rgba[:, :, 3] = mask_full
    ys, xs = np.where(mask_full > 40)
    bbox = (int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max()))
    return Image.fromarray(cv2.cvtColor(rgba, cv2.COLOR_BGRA2RGBA)), bbox, img

def crop_rgba(cut, bbox, pad_frac=0.04):
    x0, y0, x1, y1 = bbox
    pw = int((x1 - x0) * pad_frac); ph = int((y1 - y0) * pad_frac)
    box = (max(0, x0 - pw), max(0, y0 - ph), min(cut.width, x1 + pw), min(cut.height, y1 + ph))
    return cut.crop(box)

# ---------- backgrounds (synthetic, product-free zones) ----------

def ivory_bg(w, h):
    top = np.array([242, 236, 224], float)   # RGB ivory
    bot = np.array([222, 211, 190], float)
    g = np.linspace(0, 1, h)[:, None, None]
    arr = top[None, None, :] * (1 - g) + bot[None, None, :] * g
    arr = np.repeat(arr, w, axis=1)
    yy, xx = np.mgrid[0:h, 0:w]
    r2 = ((xx - w/2) / (w/2)) ** 2 + ((yy - h/2) / (h/2)) ** 2
    vig = 1 - 0.10 * np.clip(r2 - 0.35, 0, 1)
    return Image.fromarray((arr * vig[..., None]).clip(0, 255).astype(np.uint8), 'RGB')

def dark_bg(w, h, glow=True):
    yy, xx = np.mgrid[0:h, 0:w]
    cx, cy = w/2, h*0.42
    r = np.sqrt(((xx-cx)/(w*0.62))**2 + ((yy-cy)/(h*0.62))**2)
    base = np.clip(1 - r, 0, 1) ** 1.6
    c_in = np.array([44, 44, 48], float)   # charcoal
    c_out = np.array([11, 11, 13], float)  # near black
    arr = c_out[None, None, :] + (c_in - c_out)[None, None, :] * base[..., None]
    if glow:  # restrained warm-gold ambience behind product
        gr = np.sqrt(((xx-cx)/(w*0.5))**2 + ((yy-cy)/(h*0.42))**2)
        warm = (np.clip(1 - gr, 0, 1) ** 2.4)[..., None] * np.array([36, 26, 12])[None, None, :]
        arr = arr + warm
    return Image.fromarray(arr.clip(0, 255).astype(np.uint8), 'RGB')

def soft_shadow(size_w, size_h, blur=42, alpha=95):
    s = Image.new('RGBA', (size_w, size_h), (0, 0, 0, 0))
    d = ImageDraw.Draw(s)
    d.ellipse([size_w*0.10, size_h*0.30, size_w*0.90, size_h*0.78], fill=(8, 8, 10, alpha))
    return s.filter(ImageFilter.GaussianBlur(blur))

def paste_with_shadow(base, cut, box_w, center_xy, shadow_scale=1.18, dy=0):
    ratio = cut.height / cut.width
    tgt = cut.resize((box_w, int(box_w * ratio)), Image.LANCZOS)
    sh = soft_shadow(int(box_w*shadow_scale), int(tgt.height*shadow_scale*0.7))
    sh_x = center_xy[0] - sh.width // 2
    sh_y = center_xy[1] - tgt.height // 2 + int(tgt.height*0.38) + dy
    base.alpha_composite(sh, (sh_x, sh_y))
    x = center_xy[0] - box_w // 2
    y = center_xy[1] - tgt.height // 2 + dy
    base.alpha_composite(tgt, (x, y))
    return tgt, (x, y)

def rr_frame(canvas, tile, xy, radius=26, border=None):
    """paste tile (RGB PIL) into rounded rect with anti-aliased mask"""
    w, h = tile.size
    m = Image.new('L', (w*4, h*4), 0)
    ImageDraw.Draw(m).rounded_rectangle([0, 0, w*4-1, h*4-1], radius=radius*4, fill=255)
    m = m.resize((w, h), Image.LANCZOS)
    canvas.paste(tile, xy, m)
    if border:
        ImageDraw.Draw(canvas).rounded_rectangle([xy[0], xy[1], xy[0]+w, xy[1]+h], radius=radius, outline=border, width=2)

# ---------- detail crops from the real source ----------

def detail_tiles(fn, bbox_img, bbox, names):
    """Crop real regions of the cleaned master based on product bbox."""
    img = bbox_img
    x0, y0, x1, y1 = bbox
    bw, bh = x1-x0, y1-y0
    defs = {
        'stone':  (x0-0.06*bw, y0-0.08*bh, x0+1.06*bw, y0+0.62*bh),
        'band':   (x0-0.10*bw, y0+0.42*bh, x0+0.95*bw, y0+1.12*bh),
        'profile':(x0+0.30*bw, y0-0.06*bh, x0+1.22*bw, y0+0.72*bh),
        'base':   (x0-0.05*bw, y0+0.55*bh, x0+1.05*bw, y0+1.15*bh),
    }
    out = []
    for nmx in names:
        a = defs[nmx]
        box = (int(max(0,a[0])), int(max(0,a[1])), int(min(img.shape[1],a[2])), int(min(img.shape[0],a[3])))
        t = img[box[1]:box[3], box[0]:box[2]]
        out.append((nmx, Image.fromarray(cv2.cvtColor(t, cv2.COLOR_BGR2RGB))))
    return out

def square(t):
    s = min(t.size)
    return ImageOps.fit(t, (s, s), Image.LANCZOS)

