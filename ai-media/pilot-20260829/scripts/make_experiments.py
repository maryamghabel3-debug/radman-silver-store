# ---------- variant builders ----------

def build_neutral(cut, bbox, img):
    W = H = 1600
    bg = ivory_bg(W, H).convert('RGBA')
    paste_with_shadow(bg, cut, int(W*0.80), (W//2, int(H*0.50)))
    return bg.convert('RGB')

def build_dark(cut, bbox, img):
    W = H = 1600
    bg = dark_bg(W, H).convert('RGBA')
    d = ImageDraw.Draw(bg)
    d.rectangle([W*0.30, H*0.862, W*0.70, H*0.868], fill=GOLD)  # restrained gold baseline
    paste_with_shadow(bg, cut, int(W*0.76), (W//2, int(H*0.46)), shadow_scale=1.25)
    return bg.convert('RGB')

def build_post(cut, bbox, img, title_hint):
    W, H = 1080, 1350
    bg = dark_bg(W, H).convert('RGBA')
    d = ImageDraw.Draw(bg)
    d.rectangle([W*0.36, 96, W*0.64, 99], fill=GOLD)  # text-free master: divider only
    hero_w = int(W*0.84)
    hero, (hx, hy) = paste_with_shadow(bg, cut, hero_w, (W//2, int(H*0.375)))
    tiles = detail_tiles(title_hint, img, bbox, ['stone', 'band', 'profile', 'base'])
    tw = int(W*0.196); gap = (W - 4*tw) // 5
    y = int(H*0.685)
    for i, (nm, t) in enumerate(tiles):
        x = gap + i*(tw+gap)
        rr_frame(bg, square(t).resize((tw, tw), Image.LANCZOS), (x, y), radius=18, border=GOLD)
    d.rectangle([W*0.30, y+tw+58, W*0.70, y+tw+61], fill=GOLD)
    return bg.convert('RGB')

def build_story(cut, bbox, img, title_hint):
    W, H = 1080, 1920
    bg = dark_bg(W, H).convert('RGBA')
    d = ImageDraw.Draw(bg)
    hero_w = int(W*0.92)
    hero_h = int(hero_w * cut.height / cut.width)
    hero, (hx, hy) = paste_with_shadow(bg, cut, hero_w, (W//2, int(H*0.36)))
    d.rectangle([W*0.34, hy+hero_h+46, W*0.66, hy+hero_h+49], fill=GOLD)  # text-free master
    tiles = detail_tiles(title_hint, img, bbox, ['stone', 'band', 'base'])
    tw = int(W*0.26); gap = (W - 3*tw) // 4
    y = int(H*0.775)
    for i, (nm, t) in enumerate(tiles):
        x = gap + i*(tw+gap)
        rr_frame(bg, square(t).resize((tw, tw), Image.LANCZOS), (x, y), radius=18, border=GOLD)
    return bg.convert('RGB')

def build_ab(canvas_builder, cut, bbox, img, logo_path, logo_w, logo_pos):
    canvas = canvas_builder.convert('RGBA')
    logo = Image.open(logo_path).convert('RGBA')
    r = logo_w / logo.width
    logo = logo.resize((logo_w, int(logo.height*r)), Image.LANCZOS)
    if logo_pos == 'bottom-center':
        pos = ((canvas.width - logo.width)//2, canvas.height - logo.height - int(canvas.height*0.045))
    else:
        pos = (int(canvas.width*0.06), int(canvas.height*0.05))
    canvas.alpha_composite(logo, pos)
    return canvas.convert('RGB')

